/**
 * `docs/content-pack-report.md`: fixture pass rates by rule folder, every failing fixture
 * with the engine's reason, unsupported rules, rules without content and unusable content
 * files. The report has no timestamp, so it only changes when the content, the rules or
 * the engine change.
 */
import { posix } from 'node:path';
import type { ContentValidation, RuleOutcome } from './validate.js';

export interface ReportOptions {
  /** Rules and content folders as shown to the reader. */
  rulesDir: string;
  contentDir: string;
  failuresFile: string;
  pruned: boolean;
}

export interface ContentStats {
  fixtures: number;
  passed: number;
  positives: number;
  positivesPassed: number;
  negatives: number;
  negativesPassed: number;
  rulesAllPassed: number;
}

const number = new Intl.NumberFormat('en-US');

/** One decimal, rounded down, so 2,428 of 2,429 reads 99.9% rather than 100.0%. */
export function percent(part: number, total: number): string {
  return total === 0 ? '—' : `${(Math.floor((1000 * part) / total) / 10).toFixed(1)}%`;
}

export function contentStats(rules: readonly RuleOutcome[]): ContentStats {
  const fixtures = rules.flatMap((rule) => rule.fixtures);
  const positives = fixtures.filter((f) => f.kind === 'positive');
  const negatives = fixtures.filter((f) => f.kind === 'negative');
  return {
    fixtures: fixtures.length,
    passed: fixtures.filter((f) => f.passed).length,
    positives: positives.length,
    positivesPassed: positives.filter((f) => f.passed).length,
    negatives: negatives.length,
    negativesPassed: negatives.filter((f) => f.passed).length,
    rulesAllPassed: rules.filter((rule) => rule.fixtures.every((f) => f.passed)).length,
  };
}

const ratio = (part: number, total: number) =>
  `${number.format(part)} / ${number.format(total)} (${percent(part, total)})`;

/** Short summary printed by the CLI. */
export function contentSummary(validation: ContentValidation): string {
  const stats = contentStats(validation.evaluated);
  return [
    `content files: ${number.format(validation.contentFiles)} (malformed ${validation.malformed.length}, without a rule ${validation.orphans.length}, for other SigmaHQ folders ${validation.otherFolders})`,
    `rules evaluated: ${number.format(validation.evaluated.length)}; unsupported by the engine: ${validation.unsupported.length}; correlation playbooks (not evaluated): ${validation.playbookOnly.length}; rules without content: ${validation.missing.length}`,
    `fixtures passing: ${ratio(stats.passed, stats.fixtures)}`,
    `  positives matching: ${ratio(stats.positivesPassed, stats.positives)}`,
    `  negatives not matching: ${ratio(stats.negativesPassed, stats.negatives)}`,
    `rules whose fixtures all pass: ${ratio(stats.rulesAllPassed, validation.evaluated.length)}`,
  ].join('\n');
}

/** Text inside a Markdown code span; backticks would end it. */
function code(text: string): string {
  return `\`${text.replaceAll('`', "'")}\``;
}

/** Plain text in Markdown: no HTML, no emphasis, no table breaks. */
function plain(text: string): string {
  return text.replace(/[\\`*_[\]<>|]/g, (c) => `\\${c}`).replace(/\s+/g, ' ');
}

function folderRows(rules: readonly RuleOutcome[]): string[] {
  const folders = new Map<string, RuleOutcome[]>();
  for (const rule of rules) {
    const folder = posix.dirname(rule.rulePath);
    folders.set(folder, [...(folders.get(folder) ?? []), rule]);
  }
  return [...folders.entries()]
    .sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
    .map(([folder, list]) => {
      const s = contentStats(list);
      return `| ${code(folder)} | ${number.format(list.length)} | ${number.format(s.rulesAllPassed)} | ${number.format(s.passed)} / ${number.format(s.fixtures)} | ${percent(s.passed, s.fixtures)} |`;
    });
}

export function buildContentReport(validation: ContentValidation, options: ReportOptions): string {
  const stats = contentStats(validation.evaluated);
  const lines: string[] = [
    '# Content pack report',
    '',
    'Generated by `npm run content:validate`; do not edit by hand. Every fixture event of every content file is evaluated directly against its rule\'s compiled detection with Centinela\'s engine: positive fixtures must match, negative fixtures must not. Logsource routing is not involved. Keyword searches read the event\'s `message` field, or the event\'s JSON text when it has none. Correlation rules have a playbook only: a correlation cannot be tested with single events.',
    '',
    `- Rules folder: ${code(options.rulesDir)}`,
    `- Content folder: ${code(options.contentDir)}`,
    `- Failures file: ${code(options.failuresFile)}${options.pruned ? ' (failing fixtures were moved to the rejected folder with `--prune`)' : ''}`,
    '',
    '## Summary',
    '',
    '| Measure | Value |',
    '| --- | ---: |',
    `| Sigma rules in the rules folder (not deprecated) | ${number.format(validation.rulesTotal)} |`,
    `| Rules the engine cannot compile | ${number.format(validation.rulesUnsupported)} |`,
    `| Rule files that failed to load | ${number.format(validation.ruleLoadErrors)} |`,
    `| Content files | ${number.format(validation.contentFiles)} |`,
    `| Malformed content files | ${number.format(validation.malformed.length)} |`,
    `| Content files for other SigmaHQ folders (skipped) | ${number.format(validation.otherFolders)} |`,
    `| Content files without a rule | ${number.format(validation.orphans.length)} |`,
    `| Rules without content | ${number.format(validation.missing.length)} |`,
    `| Rules with content not supported by the engine | ${number.format(validation.unsupported.length)} |`,
    `| Correlation rules with a playbook only (not evaluated) | ${number.format(validation.playbookOnly.length)} |`,
    `| Rules evaluated | ${number.format(validation.evaluated.length)} |`,
    `| Rules whose fixtures all pass | ${ratio(stats.rulesAllPassed, validation.evaluated.length)} |`,
    `| **Fixtures passing** | **${ratio(stats.passed, stats.fixtures)}** |`,
    `| Positive fixtures that match | ${ratio(stats.positivesPassed, stats.positives)} |`,
    `| Negative fixtures that do not match | ${ratio(stats.negativesPassed, stats.negatives)} |`,
    '',
    '## Pass rate by rule folder',
    '',
    '| Folder | Rules | Rules all passing | Fixtures passing | Rate |',
    '| --- | ---: | ---: | ---: | ---: |',
    ...folderRows(validation.evaluated),
    '',
    '## Failing fixtures',
    '',
  ];

  const failing = validation.evaluated.filter((rule) => rule.fixtures.some((f) => !f.passed));
  if (failing.length === 0) lines.push('None.');
  for (const rule of failing) {
    lines.push(`### ${plain(rule.title)}`, '', `${code(rule.rulePath)} · id ${code(rule.ruleId)}`, '');
    for (const fixture of rule.fixtures.filter((f) => !f.passed)) {
      lines.push(
        `- ${fixture.kind} #${fixture.index}: ${plain(fixture.description)}`,
        `  - reason: ${code(fixture.reason ?? '')}`,
      );
    }
    lines.push('');
  }

  lines.push('## Rules with content not supported by the engine', '');
  if (validation.unsupported.length === 0) lines.push('None.');
  for (const rule of validation.unsupported) {
    lines.push(`- ${code(rule.rulePath)} (${plain(rule.title)}): ${code(rule.reason)}, ${rule.fixtures} fixtures not evaluated`);
  }

  lines.push('', '## Correlation rules with a playbook only', '');
  if (validation.playbookOnly.length === 0) lines.push('None.');
  for (const rule of validation.playbookOnly) {
    const ignored =
      rule.ignoredFixtures > 0 ? `; ${rule.ignoredFixtures} fixtures in the file were ignored` : '';
    lines.push(`- ${code(rule.rulePath)} (${plain(rule.title)})${ignored}`);
  }

  lines.push('', '## Rules without content', '');
  if (validation.missing.length === 0) lines.push('None.');
  for (const rule of validation.missing) lines.push(`- ${code(rule.rulePath)} (${plain(rule.title)})`);

  lines.push('', '## Unusable content files', '');
  const issues = [...validation.malformed, ...validation.orphans];
  if (issues.length === 0) lines.push('None.');
  for (const issue of issues) lines.push(`- ${code(issue.file)}: ${plain(issue.reason)}`);

  return `${lines.join('\n').trimEnd()}\n`;
}
